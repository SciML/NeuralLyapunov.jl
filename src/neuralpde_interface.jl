struct PINNOutput{N}
    net::N
end

(φ::PINNOutput)(x::AbstractMatrix, θ) = NeuralPDE.trial_function(φ.net, θ)(x)
(φ::PINNOutput)(x::AbstractVector, θ) = vec(φ(reshape(x, :, 1), θ))

"""
    get_network_and_parameters(prob, res)

Return `(phi, θ)` describing the neural network trained by NeuralPDE.jl, in the form expected
by [`get_numerical_lyapunov_function`](@ref) and [`get_policy`](@ref).

`phi` is a `Vector` with one entry per dependent variable of the `PDESystem`, each a function
`phi[i](x, θ[:φi])` that evaluates the corresponding network output on a state vector or
columnwise on a matrix of states. `θ` is a `NamedTuple` with keys `:φ1`, `:φ2`, ... holding
the flat parameter vector of each network.

# Arguments
  - `prob`: the `OptimizationProblem` returned by `NeuralPDE.discretize`.
  - `res`: the trained parameters, given as the solution returned by `solve(prob, ...)` (a
    `PDENoTimeSolution` or `OptimizationSolution`) or as a flat parameter vector of the same
    layout as `prob.u0`.
"""
function get_network_and_parameters(prob::SciMLBase.OptimizationProblem, res)
    md = pinn_metadata(prob)
    md === nothing && throw(
        ArgumentError(
            "`prob` was not generated by `NeuralPDE.discretize` with a `PhysicsInformedNN`."
        )
    )
    state = ProblemState(; u = _trained_parameters(res), p = prob.p)
    phi = [PINNOutput(net) for net in md.networks]
    keys = Tuple(Symbol(:φ, i) for i in eachindex(phi))
    θ = NamedTuple{keys}(Tuple(getsym(prob, net.θ)(state) for net in md.networks))
    return phi, θ
end

_trained_parameters(u::AbstractVector) = u
_trained_parameters(res::SciMLBase.PDENoTimeSolution) = res.original_sol.u
_trained_parameters(res::SciMLBase.AbstractOptimizationSolution) = res.u
